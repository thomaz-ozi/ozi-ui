/**
 * components/ozi-search/lang/es.js
 */
(function (window) {
    'use strict';
    var lang = window.OZI && window.OZI.lang;
    if (!lang || !lang.register) return;
    lang.register('es', {
        search: {
            pagination:       'Paginación',
            prev:             'Anterior',
            next:             'Siguiente',
            page:             'Página'
        }
    });
})(window);