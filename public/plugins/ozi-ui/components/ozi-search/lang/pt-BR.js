/**
 * components/ozi-search/lang/pt-BR.js
 */
(function (window) {
    'use strict';
    var lang = window.OZI && window.OZI.lang;
    if (!lang || !lang.register) return;
    lang.register('pt-BR', {
        search: {
            pagination:       'Paginação',
            prev:             'Anterior',
            next:             'Próxima',
            page:             'Página'
        }
    });
})(window);